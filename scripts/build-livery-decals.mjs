/**
 * Builds the livery's logo textures from the BadCodes artwork: trims the transparent margins, downsizes
 * and writes public/models/<name>.<8-char hash>.png (the /models cache header is immutable, so a
 * changed file is a new name), then src/models/f1/decals.ts with the URLs and sizes.
 *
 * - mark: the bc monogram, RGBA in its own colours (gradient b, white c), 512 px wide.
 * - wordmark: the BadCodes wordmark as a one-channel mask (its alpha), 1024 px wide. The shader
 *   fills the mask with whatever colour the livery names, so one file serves every colour. The
 *   artwork sets "codes" as an outline; the outlines are filled (lib/solid-outline.mjs) so both words
 *   take the colour as solid letters.
 *
 * The two source PNGs (transparent background) are not in the repo; the built textures are, so this is
 * only needed to change the artwork. Pass them as arguments or through the environment:
 *   node scripts/build-livery-decals.mjs <mark.png> <wordmark.png>
 *   BC_MARK_PNG=<mark.png> BC_WORDMARK_PNG=<wordmark.png> node scripts/build-livery-decals.mjs
 */
import { createHash } from "node:crypto";
import { readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { ROOT } from "./lib/dev-server.mjs";
import { fillOutlinedGlyphs } from "./lib/solid-outline.mjs";

const MARK_SRC = process.argv[2] ?? process.env.BC_MARK_PNG;
const WORDMARK_SRC = process.argv[3] ?? process.env.BC_WORDMARK_PNG;
if (!MARK_SRC || !WORDMARK_SRC) {
  console.error("Usage: node scripts/build-livery-decals.mjs <mark.png> <wordmark.png>\n   or: set BC_MARK_PNG and BC_WORDMARK_PNG");
  process.exit(1);
}
const MODELS = path.join(ROOT, "public", "models");
const OUT_TS = path.join(ROOT, "src", "models", "f1", "decals.ts");

/** The wordmark's alpha with "codes" (columns 0.39 to 0.905 of the width, before the registered mark) filled solid. */
async function solidWordmark(img) {
  const { data, info } = await img.extractChannel("alpha").raw().toBuffer({ resolveWithObject: true });
  fillOutlinedGlyphs(data, info.width, info.height, { from: info.width * 0.39, to: info.width * 0.905 });
  return sharp(data, { raw: { width: info.width, height: info.height, channels: 1 } }).png({ compressionLevel: 9, effort: 10 });
}

const JOBS = [
  { id: "mark", file: MARK_SRC, width: 512, pad: 4, build: (img) => img.png({ compressionLevel: 9, effort: 10 }) },
  { id: "wordmark", file: WORDMARK_SRC, width: 1024, pad: 8, build: solidWordmark },
];

const out = {};
for (const job of JOBS) {
  const { data: trimmed } = await sharp(job.file).ensureAlpha().trim().toBuffer({ resolveWithObject: true });
  const sized = await sharp(trimmed).resize({ width: job.width - 2 * job.pad }).extend({ top: job.pad, bottom: job.pad, left: job.pad, right: job.pad, background: { r: 0, g: 0, b: 0, alpha: 0 } }).toBuffer();
  const { data, info } = await (await job.build(sharp(sized))).toBuffer({ resolveWithObject: true });
  const hash = createHash("sha256").update(data).digest("hex").slice(0, 8);
  const name = `bc-${job.id}.${hash}.png`;
  for (const f of readdirSync(MODELS)) if (new RegExp(`^bc-${job.id}\.[0-9a-f]{8}\.png$`).test(f) && f !== name) rmSync(path.join(MODELS, f));
  writeFileSync(path.join(MODELS, name), data);
  out[job.id] = { url: `/models/${name}`, width: info.width, height: info.height, bytes: data.length };
  console.log(`${name}: ${info.width}x${info.height}, ${data.length} bytes`);
}

writeFileSync(
  OUT_TS,
  `/**
 * The livery's logo textures, generated by scripts/build-livery-decals.mjs from the BadCodes artwork:
 * do not edit by hand. \`aspect\` is width over height of the file, margins included.
 */
export const DECALS = {
  mark: { url: "${out.mark.url}", width: ${out.mark.width}, height: ${out.mark.height}, aspect: ${(out.mark.width / out.mark.height).toFixed(4)} },
  wordmark: { url: "${out.wordmark.url}", width: ${out.wordmark.width}, height: ${out.wordmark.height}, aspect: ${(out.wordmark.width / out.wordmark.height).toFixed(4)} },
} as const;
`,
);
console.log(`total ${out.mark.bytes + out.wordmark.bytes} bytes`);
